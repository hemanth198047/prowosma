export function applyTheme(theme) {
  const root = document.documentElement;
  root.style.setProperty("--brand-50", theme.brand50);
  root.style.setProperty("--brand-100", theme.brand100);
  root.style.setProperty("--brand-200", theme.brand200);
  root.style.setProperty("--brand-400", theme.brand400);
  root.style.setProperty("--brand-500", theme.brand500);
  root.style.setProperty("--brand-600", theme.brand600);
  root.style.setProperty("--brand-700", theme.brand700);
  root.style.setProperty("--brand-900", theme.brand900);

  // Update body background photo
  document.body.style.background = `${theme.bgPage} url('${theme.photo}') center/cover fixed`;

  // Update page header
  const headers = document.querySelectorAll(".page-header-block");
  headers.forEach((h) => {
    h.style.background = `linear-gradient(135deg, ${theme.headerBg}), url('${theme.photo}') center/cover no-repeat`;
    h.style.borderColor = theme.headerBorder;
  });

  // Store in localStorage
  localStorage.setItem("prowosma-theme", theme.id);
  localStorage.setItem("prowosma-theme-data", JSON.stringify(theme));
}

export function initTheme() {
  const saved = localStorage.getItem("prowosma-theme-data");
  if (saved) {
    try {
      applyTheme(JSON.parse(saved));
    } catch { /* malformed saved theme — keep default */ }
  }
}
